// Build-time snapshot only: never import Vite, auth, API clients or database code.
import { readFileSync, readdirSync, mkdirSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, relative, sep } from 'node:path';
import { runInNewContext } from 'node:vm';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(resolve(root, 'frontend-mobile/package.json'));
const ts = require('typescript');
const web = resolve(root, 'frontend-web');
const mobile = resolve(root, 'frontend-mobile');
const publicRoot = resolve(web, 'public');
const assets = new Set(readdirSync(resolve(publicRoot, 'museum'), { recursive: true })
  .filter(name => /\.(jpg|mp4|vtt)$/.test(name)).map(name => '/museum/' + name.replaceAll('\\', '/')));
const cache = new Map();
function load(name) {
  if (name === 'publicMediaAssets') return { publicMuseumAssetPaths: assets };
  if (cache.has(name)) return cache.get(name);
  if (!['publicVideos', 'homeImages', 'exhibitions'].includes(name)) throw new Error('Unexpected museum dependency');
  const exports = {};
  const source = readFileSync(resolve(web, 'src/features/museum', name + '.ts'), 'utf8');
  const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } });
  runInNewContext(outputText, { exports, require: path => load(path.replace('./', '')) });
  cache.set(name, exports);
  return exports;
}
function homeConstant(name) {
  const source = ts.createSourceFile('home.tsx', readFileSync(resolve(web, 'src/pages/MuseumHomePage.tsx'), 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  let initializer;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(source) === name) initializer = node.initializer.getText(source);
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (!initializer) throw new Error('Missing Web constant: ' + name);
  const exports = {};
  const { outputText } = ts.transpileModule('export const value = ' + initializer, { compilerOptions: { module: ts.ModuleKind.CommonJS } });
  runInNewContext(outputText, { exports });
  return exports.value;
}
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
export function syncMuseumMobile(write = false) {
  const images = load('homeImages').museumHomeImages;
  const videos = load('publicVideos').getPublishedPublicVideos();
  const exhibitions = load('exhibitions').getPublishedExhibitions();
  const paths = [...new Set([...Object.values(images).map(image => image.src), ...videos.map(video => video.posterUrl).filter(Boolean)])];
  const imageHashes = {};
  for (const path of paths) {
    if (!/^\/museum\/(images|posters)\/[a-z0-9-]+\.jpg$/.test(path) || !assets.has(path)) throw new Error('Unsupported/missing public image');
    const source = resolve(publicRoot, '.' + path);
    const target = resolve(mobile, 'assets', '.' + path);
    if (!target.startsWith(resolve(mobile, 'assets/museum') + sep)) throw new Error('Invalid asset destination');
    imageHashes[path] = hash(readFileSync(source));
    if (write) { mkdirSync(dirname(target), { recursive: true }); copyFileSync(source, target); }
    if (!existsSync(target) || hash(readFileSync(target)) !== imageHashes[path]) throw new Error('Museum image drift: ' + path);
  }
  const snapshot = { images, topics: homeConstant('editorialTopics'), narrationLanguages: homeConstant('narrationLanguages'), languages: load('publicVideos').museumVideoLanguages, videos, exhibitions, imageHashes, playback: 'EXTERNAL_SOURCE_ONLY' };
  const json = JSON.stringify(snapshot, null, 2) + '\n';
  const feature = resolve(mobile, 'src/features/museum');
  const map = '// Generated by scripts/museum-mobile-sync.mjs from public Web assets.\nexport const museumAssets: Record<string, number> = {\n' + paths.map(path => `  ${JSON.stringify(path)}: require(${JSON.stringify('../../../assets' + path)}),`).join('\n') + '\n};\n';
  for (const [name, content] of [['catalog.generated.json', json], ['assets.generated.ts', map]]) {
    const target = resolve(feature, name);
    if (write) { mkdirSync(feature, { recursive: true }); writeFileSync(target, content); }
    if (!existsSync(target) || readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error('Museum snapshot drift: ' + relative(root, target));
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  syncMuseumMobile(process.argv.includes('--write'));
  process.stdout.write('Museum public snapshot and image hashes match Web.\n');
}
