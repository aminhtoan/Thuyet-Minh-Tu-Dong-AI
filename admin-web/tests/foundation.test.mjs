import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';

test('centralized mock validation and dashboard contract', async () => {
  const server = await createServer({ configFile: false, cacheDir: 'node_modules/.vite-foundation-test', optimizeDeps: { noDiscovery: true }, server: { middlewareMode: true, hmr: false }, appType: 'custom' });
  try {
    const { validateMockAdminLogin } = await server.ssrLoadModule('/src/mocks/adminAuth.mock.ts');
    assert.ok(validateMockAdminLogin('', ''));
    assert.ok(validateMockAdminLogin('invalid', 'demo'));
    assert.ok(validateMockAdminLogin('admin@example.com', '   '));
    assert.equal(validateMockAdminLogin(' admin@example.com ', 'demo'), null);
    const { createAdminDashboardMock } = await server.ssrLoadModule('/src/mocks/adminDashboard.mock.ts');
    const data = createAdminDashboardMock();
    assert.deepEqual(Object.values(data.stats), [128, 246, 8, 3]);
    assert.equal(data.recentProjects.length, 5);
    assert.equal(data.processingJobs.length, 5);
    assert.equal(data.recentActivities.length, 6);
    assert.equal(data.jobSummary.processing, data.stats.processing);
    assert.equal(data.jobSummary.failed, data.stats.failed);
    assert.ok(data.recentProjects.every(project => ['COMPLETED', 'PROCESSING_VIDEO', 'FAILED', 'DRAFT', 'TRANSLATING'].includes(project.status)));
    assert.ok(data.recentActivities.every(item => item.userId && item.entityId && item.action && Number.isFinite(Date.parse(item.createdAt))));
    const { adminDashboardService } = await server.ssrLoadModule('/src/services/adminDashboardService.ts');
    const snapshot = await adminDashboardService.getDashboard({ latencyMs: 0 });
    snapshot.recentProjects[0].name = 'mutated';
    assert.notEqual((await adminDashboardService.getDashboard({ latencyMs: 0 })).recentProjects[0].name, 'mutated');
    await assert.rejects(adminDashboardService.getDashboard({ scenario: 'error', latencyMs: 0 }));
    assert.equal((await adminDashboardService.getDashboard({ latencyMs: 0 })).stats.totalCustomers, 128);
    const empty = await adminDashboardService.getDashboard({ scenario: 'empty', latencyMs: 0 });
    assert.ok(Object.values(empty.stats).every(value => value === 0));
    assert.ok(Object.values(empty.jobSummary).every(value => value === 0));
    assert.deepEqual([empty.recentProjects.length, empty.processingJobs.length, empty.recentActivities.length], [0, 0, 0]);
    const abort = new AbortController();
    const pending = adminDashboardService.getDashboard({ latencyMs: 1000, signal: abort.signal });
    abort.abort();
    await assert.rejects(pending, { name: 'AbortError' });
    await assert.rejects(adminDashboardService.getDashboard({ signal: abort.signal }), { name: 'AbortError' });
    const { clampProgress, formatRelativeTime, jobTypeLabels } = await server.ssrLoadModule('/src/utils/dashboardFormat.ts');
    for (const [input, output] of [[NaN, 0], [Infinity, 0], [-3, 0], [115, 100], [42.4, 42]]) assert.equal(clampProgress(input), output);
    const now = Date.parse('2026-09-26T10:00:00+07:00');
    assert.equal(formatRelativeTime(new Date(now).toISOString(), now), 'Vừa xong');
    assert.equal(formatRelativeTime(new Date(now - 300000).toISOString(), now), '5 phút trước');
    assert.equal(formatRelativeTime(new Date(now - 7200000).toISOString(), now), '2 giờ trước');
    assert.equal(formatRelativeTime('invalid', now), 'Chưa cập nhật');
    assert.equal(Object.keys(jobTypeLabels).length, 4);
    const { navigation } = await server.ssrLoadModule('/src/components/layout/navigation.ts');
    assert.deepEqual(navigation.flatMap(group => group.items.map(item => item.to)), ['/dashboard', '/users', '/projects', '/jobs', '/languages', '/voices', '/logs', '/settings']);

    const { adminCustomerService } = await server.ssrLoadModule('/src/services/adminCustomerService.ts');
    const { adminCustomerScenario } = await server.ssrLoadModule('/src/mocks/adminCustomerScenario.ts');
    adminCustomerService.resetForTests();
    const { adminProjectService } = await server.ssrLoadModule('/src/services/adminProjectService.ts');
    const { adminJobService } = await server.ssrLoadModule('/src/services/adminJobService.ts');
    const { adminOperationsScenario } = await server.ssrLoadModule('/src/mocks/adminOperationsScenario.ts');
    adminJobService.resetForTests();
    const { adminLanguageService } = await server.ssrLoadModule('/src/services/adminLanguageService.ts');
    const { adminVoiceService } = await server.ssrLoadModule('/src/services/adminVoiceService.ts');
    const { adminLogService } = await server.ssrLoadModule('/src/services/adminLogService.ts');
    const { adminSettingsService } = await server.ssrLoadModule('/src/services/adminSettingsService.ts');
    const { adminSystemScenario } = await server.ssrLoadModule('/src/mocks/adminSystemScenario.ts');
    const { resetSystem } = await server.ssrLoadModule('/src/services/adminSystemStore.ts');
    resetSystem();
    const languages = await adminLanguageService.getLanguages({ latencyMs: 0 });
    assert.deepEqual([languages.length, languages.filter(x => x.isActive).length, languages.reduce((n, x) => n + x.voiceCount, 0)], [6, 4, 12]);
    await assert.rejects(adminLanguageService.createLanguage({ code: ' VI ', name: 'Duplicate', nativeName: 'Trùng', isActive: true }, { latencyMs: 0 }), /DUPLICATE_CODE/);
    const french = await adminLanguageService.updateLanguage('lang-fr', { name: 'French updated', nativeName: 'Français', isActive: true }, { latencyMs: 0 });
    assert.deepEqual([french.code, french.isActive], ['fr', true]);
    assert.equal((await adminLanguageService.setLanguageActive('lang-fr', false, { latencyMs: 0 })).isActive, false);
    const voices = await adminVoiceService.getVoices({ latencyMs: 0 });
    assert.equal(voices.length, 12); assert.ok(voices.every(v => languages.some(l => l.id === v.languageId)));
    await assert.rejects(adminVoiceService.createVoice({ name: 'Trùng', languageId: 'lang-vi', gender: 'FEMALE', provider: 'Mock AI', providerVoiceId: 'vi-female-01', description: '', isActive: true }, { latencyMs: 0 }), /DUPLICATE/);
    assert.equal((await adminVoiceService.setVoiceActive('voice-vi-1', false, { latencyMs: 0 })).isActive, false);
    const logs = await adminLogService.getLogs({ limit: 10, latencyMs: 0 });
    assert.deepEqual([logs.pagination.total, logs.items.length, logs.pagination.totalPages], [27, 10, 3]);
    assert.ok((await adminLogService.getLogs({ role: 'ADMIN', days: 7, latencyMs: 0 })).items.every(x => x.userRole === 'ADMIN'));
    assert.equal((await adminLogService.getLogById('log-001', { latencyMs: 0 })).id, 'log-001');
    const settings = await adminSettingsService.getSettings({ latencyMs: 0 });
    assert.equal(settings.maxUploadMb, 500); assert.equal(Object.keys(settings).some(k => /secret|key|password/i.test(k)), false);
    const updatedSettings = await adminSettingsService.updateSettings({ ...settings, concurrentJobs: 4, defaultVoiceSpeed: 1.2 }, { latencyMs: 0 });
    assert.deepEqual([updatedSettings.concurrentJobs, updatedSettings.defaultVoiceSpeed], [4, 1.2]);
    await assert.rejects(adminSettingsService.updateSettings({ ...settings, maxUploadMb: 0 }, { latencyMs: 0 }), /VALIDATION/);
    adminSystemScenario.mode = 'empty'; assert.deepEqual(await adminLanguageService.getLanguages({ latencyMs: 0 }), []);
    adminSystemScenario.mode = 'error'; await assert.rejects(adminVoiceService.getVoices({ latencyMs: 0 }));
    adminSystemScenario.mode = 'success'; resetSystem();
    const projects = await adminProjectService.getProjects({ latencyMs: 0 });
    assert.equal(projects.summary.total, 18); assert.equal(projects.items.length, 10); assert.equal(projects.pagination.totalPages, 2);
    assert.ok(projects.items.every(project => project.userId.startsWith('kh-')));
    assert.ok((await adminProjectService.getProjects({ search: 'nguyễn văn', language: 'vi', latencyMs: 0 })).items.length > 0);
    const project = await adminProjectService.getProjectById('project-001', { latencyMs: 0 });
    assert.equal(project.customerName, 'Nguyễn Văn An');
    assert.ok((await adminProjectService.getProjectJobs('project-001', { latencyMs: 0 })).every(job => job.projectId === 'project-001'));
    assert.equal(await adminProjectService.getProjectById('missing', { latencyMs: 0 }), null);
    const jobs = await adminJobService.getJobs({ latencyMs: 0 });
    assert.equal(jobs.pagination.total, 26); assert.equal(jobs.items.length, 10);
    assert.ok((await adminJobService.getJobs({ type: 'TTS', status: 'FAILED', latencyMs: 0 })).items.every(job => job.type === 'TTS' && job.status === 'FAILED'));
    const failed = (await adminJobService.getJobs({ status: 'FAILED', latencyMs: 0 })).items[0];
    const retried = await adminJobService.retryJob(failed.id, { latencyMs: 0 });
    assert.deepEqual([retried.status, retried.progress, retried.errorMessage, retried.completedAt], ['QUEUED', 0, undefined, undefined]);
    const processing = (await adminJobService.getJobs({ status: 'PROCESSING', latencyMs: 0 })).items[0];
    assert.equal((await adminJobService.cancelJob(processing.id, { latencyMs: 0 })).status, 'CANCELLED');
    const completed = (await adminJobService.getJobs({ status: 'COMPLETED', latencyMs: 0 })).items[0];
    await assert.rejects(adminJobService.cancelJob(completed.id, { latencyMs: 0 }));
    adminOperationsScenario.failNextMutation = true;
    const queued = (await adminJobService.getJobs({ status: 'QUEUED', latencyMs: 0 })).items[0];
    await assert.rejects(adminJobService.cancelJob(queued.id, { latencyMs: 0 }));
    assert.equal((await adminJobService.getJobById(queued.id, { latencyMs: 0 })).status, 'QUEUED');
    adminOperationsScenario.projectMode = 'empty'; assert.equal((await adminProjectService.getProjects({ latencyMs: 0 })).summary.total, 0);
    adminOperationsScenario.jobMode = 'error'; await assert.rejects(adminJobService.getJobs({ latencyMs: 0 }));
    adminJobService.resetForTests();
    const customers = await adminCustomerService.getCustomers({ latencyMs: 0 });
    assert.equal(customers.summary.total, 14);
    assert.equal(customers.summary.active + customers.summary.blocked, customers.summary.total);
    assert.equal(customers.items.length, 10);
    assert.equal(customers.pagination.totalPages, 2);
    assert.ok(customers.items.every(customer => customer.role === 'CUSTOMER'));
    const search = await adminCustomerService.getCustomers({ search: '  NGUYỄN VĂN ', status: 'ACTIVE', latencyMs: 0 });
    assert.deepEqual(search.items.map(customer => customer.id), ['kh-001']);
    assert.equal((await adminCustomerService.getCustomers({ status: 'BLOCKED', latencyMs: 0 })).pagination.total, customers.summary.blocked);
    assert.equal((await adminCustomerService.getCustomers({ page: 2, latencyMs: 0 })).items.length, 4);
    assert.equal((await adminCustomerService.getCustomerById('kh-001', { latencyMs: 0 })).fullName, 'Nguyễn Văn An');
    assert.equal(await adminCustomerService.getCustomerById('kh-khong-co', { latencyMs: 0 }), null);
    assert.equal((await adminCustomerService.blockCustomer('kh-001', { latencyMs: 0 })).status, 'BLOCKED');
    assert.equal((await adminCustomerService.getCustomerById('kh-001', { latencyMs: 0 })).status, 'BLOCKED');
    assert.equal((await adminCustomerService.unblockCustomer('kh-001', { latencyMs: 0 })).status, 'ACTIVE');
    adminCustomerScenario.failNextMutation = true;
    await assert.rejects(adminCustomerService.blockCustomer('kh-001', { latencyMs: 0 }));
    assert.equal((await adminCustomerService.getCustomerById('kh-001', { latencyMs: 0 })).status, 'ACTIVE');
    await assert.rejects(adminCustomerService.getCustomers({ latencyMs: 0, signal: abort.signal }), { name: 'AbortError' });
    adminCustomerScenario.mode = 'empty';
    assert.equal((await adminCustomerService.getCustomers({ latencyMs: 0 })).summary.total, 0);
    adminCustomerScenario.mode = 'error';
    await assert.rejects(adminCustomerService.getCustomers({ latencyMs: 0 }));
    adminCustomerService.resetForTests();
  } finally { await server.close(); }
});
